"""Generates the morning-import files for the v4 glassies (docs/art/IMPORT_RUNBOOK.md).

    python3 docs/art/glassy_revamp/tools/make_import_files.py

Writes (all deterministic, safe to re-run):
- docs/art/glassy_revamp/upload_list_v4.json      24 revamped glassies -> Record docs/art/glassy_revamp/roblox_assets.json
- docs/art/launch_glassies/upload_list_v4.json    12 launch glassies   -> Record docs/art/launch_glassies/roblox_assets.json
- docs/art/upload_lists/finishers_v3.json         workstream G mesh    -> Record assets/blender/round_cosmetics/finishers_v3/roblox_assets.json
- docs/art/upload_lists/hollowlight_v5.json       workstream I mesh    -> Record assets/blender/seasonal/hollowlight_v5/roblox_assets.json
- docs/art/glassy_revamp/ReleaseCrackPaths_v4.luau candidate for src/shared/Config/ReleaseCrackPaths.luau
  (hollowlight copied from the current file, every glassy from its v4 cracks.json)
Upload lists use tools/opencloud/upload_assets.py's format: {"Record", "Items": [{Key, Path, Type, Name}]}.
Per glassy: "<id>_bundle" (Model: Body + Details + Shards FBX) and "<id>_icon" (Decal: 512 px icon).
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
REVAMP = ["pop", "jam", "prism", "milk_bottle", "pickle_jar", "ketchup_bottle", "glass_cup", "water_jug", "lemonade_bottle",
          "mason_jar", "hot_sauce", "crystal_tumbler", "chime", "crescent_axe", "briar_flask", "arc_coil", "hourglass", "frostglobe",
          "rocket_pop", "prism_blade", "glass_duck", "comet", "glass_dragon", "galaxy_orb"]
LAUNCH = ["fishbowl", "cookie_jar", "glass_top", "bubble_wand", "piggy_bank", "light_bulb", "potion_flask", "honey_bear",
          "crystal_ball", "grizzly_guardian", "glass_unicorn", "glass_phoenix"]


def display(gid):
    return " ".join(w.capitalize() for w in gid.split("_"))


def glassy_items(ids):
    items = []
    for gid in ids:
        m = json.loads((ROOT / "assets/blender/glassies" / gid / "v4/manifest.json").read_text())
        assert m["fbx_roundtrip"]["passed"], gid
        items.append({"Key": gid + "_bundle", "Path": m["files"]["bundle"], "Type": "Model", "Name": "GlassClash %s v4" % display(gid)})
        items.append({"Key": gid + "_icon", "Path": m["files"]["icon"], "Type": "Decal", "Name": "GlassClash %s icon v4" % display(gid)})
    return items


def write(path, record, items):
    path = ROOT / path
    path.parent.mkdir(parents=True, exist_ok=True)
    for it in items:
        assert (ROOT / it["Path"]).exists(), it["Path"]
    path.write_text(json.dumps({"Record": record, "Items": items}, indent=1) + "\n")
    print(path.relative_to(ROOT), len(items), "items")


write("docs/art/glassy_revamp/upload_list_v4.json", "docs/art/glassy_revamp/roblox_assets.json", glassy_items(REVAMP))
write("docs/art/launch_glassies/upload_list_v4.json", "docs/art/launch_glassies/roblox_assets.json", glassy_items(LAUNCH))
write("docs/art/upload_lists/finishers_v3.json", "assets/blender/round_cosmetics/finishers_v3/roblox_assets.json",
      [{"Key": "finishers_v3", "Path": "assets/blender/round_cosmetics/finishers_v3/finishers_v3.fbx", "Type": "Model", "Name": "GlassClash Finishers v3"}])
write("docs/art/upload_lists/hollowlight_v5.json", "assets/blender/seasonal/hollowlight_v5/roblox_assets.json",
      [{"Key": "moonlantern_carriage_v5", "Path": "assets/blender/seasonal/hollowlight_v5/moonlantern_carriage_v5.fbx", "Type": "Model", "Name": "GlassClash Moonlantern Carriage v5"}])

# Crack paths: same rows as cracks.json (already Roblox hang space: x1 y1 z1 x2 y2 z2 stage).
current = (ROOT / "src/shared/Config/ReleaseCrackPaths.luau").read_text()
hollow = re.search(r"\thollowlight = \{\n.*?\n\t\},\n", current, re.S).group(0)
out = ["-- Source-projected cracks for revised native body geometry, already converted to Roblox axes.",
       "-- v4 candidate generated by docs/art/glassy_revamp/tools/make_import_files.py (hollowlight copied unchanged).",
       "return {", hollow.rstrip("\n")]
for gid in REVAMP + LAUNCH:
    rows = json.loads((ROOT / "assets/blender/glassies" / gid / "v4/cracks.json").read_text())
    out.append("\t%s = {" % gid)
    for r in rows:
        out.append("\t\t{ %s, %d }," % (", ".join("%.6f" % v for v in r[:6]), int(r[6])))
    out.append("\t},")
out.append("}")
(ROOT / "docs/art/glassy_revamp/ReleaseCrackPaths_v4.luau").write_text("\n".join(out) + "\n")
print("docs/art/glassy_revamp/ReleaseCrackPaths_v4.luau", len(REVAMP + LAUNCH) + 1, "entries")

# Release geometry (collision Radius/Center) measured from the v4 Body bounds, same method as
# docs/art/launch_glassies/tools/build_launch.py release_geometry(): Radius = horizontal half-extent, Center = depth of the
# body's vertical midpoint below the hang point. Hollowlight is copied from the current file.
geo_now = (ROOT / "src/shared/Config/ReleaseGeometry.luau").read_text()
hollow_geo = re.search(r"\thollowlight = \{[^}]*\},", geo_now).group(0)
lines = ["-- Measured from the v4 body bounds (docs/art/glassy_revamp/tools/make_import_files.py); excludes cosmetic details.",
         "return {", hollow_geo]
changes = []
for gid in REVAMP + LAUNCH:
    m = json.loads((ROOT / "assets/blender/glassies" / gid / "v4/manifest.json").read_text())
    lo, hi = next(e for e in m["meshes"] if e["role"] == "Body")["bounds_blender"]
    radius, centre = max(-lo[0], hi[0], -lo[1], hi[1]), -(lo[2] + hi[2]) / 2
    lines.append("\t%s = { Radius = %.6f, Center = %.6f }," % (gid, radius, centre))
    old = re.search(r"\t%s = \{ Radius = ([0-9.]+), Center = ([0-9.]+) \}" % gid, geo_now)
    if old and (abs(float(old.group(1)) - radius) > 0.005 or abs(float(old.group(2)) - centre) > 0.005):
        changes.append("%s %.3f/%.3f -> %.3f/%.3f" % (gid, float(old.group(1)), float(old.group(2)), radius, centre))
lines.append("}")
(ROOT / "docs/art/glassy_revamp/ReleaseGeometry_v4.luau").write_text("\n".join(lines) + "\n")
print("docs/art/glassy_revamp/ReleaseGeometry_v4.luau; changed vs src:", "; ".join(changes) or "none")
