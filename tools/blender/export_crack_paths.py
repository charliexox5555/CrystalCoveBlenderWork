"""Project crack paths onto approved glass meshes without changing the art.

Load glassclash_blender.py first, then run this through Blender MCP. Output
points are in Roblox Y-up hang-point space and require no uploaded texture.
"""
from mathutils.bvhtree import BVHTree


def export_crack_paths():
    lines = [
        (.43,.12,.49,.32), (.49,.32,.39,.48), (.39,.48,.53,.69), (.53,.69,.46,.9),
        (.49,.32,.64,.25), (.39,.48,.25,.54),
        (.53,.69,.72,.61), (.64,.25,.71,.12), (.25,.54,.18,.74), (.49,.32,.59,.47),
        (.59,.47,.75,.51), (.46,.9,.29,.8),
        (.53,.69,.63,.84), (.39,.48,.28,.32), (.28,.32,.18,.27), (.59,.47,.66,.36),
        (.46,.9,.51,.98), (.72,.61,.81,.71),
    ]
    output = ["--!strict", "-- Generated by tools/blender/export_crack_paths.py from the approved bodies.",
              "-- Coordinates follow the actual surface, in Roblox hang-point space.", "return {"]
    report = {}
    for gid in ("pop", "jam", "prism"):
        path = repo_path("assets", "blender", "glassies", gid, f"{gid}.blend")
        with bpy.data.libraries.load(path, link=False) as (available, loaded):
            loaded.scenes = available.scenes
        scene = loaded.scenes[0]
        objects = list(scene.objects)
        try:
            body = next(o for o in objects if o.type == "MESH" and re.sub(r"\.\d+$", "", o.name) == "Body")
            vertices = [body.matrix_world @ v.co for v in body.data.vertices]
            polygons = [list(p.vertices) for p in body.data.polygons]
            tree = BVHTree.FromPolygons(vertices, polygons)
            lo = Vector(tuple(min(v[i] for v in vertices) for i in range(3)))
            hi = Vector(tuple(max(v[i] for v in vertices) for i in range(3)))
            output.append(f'\t{gid} = {{')
            count = 0
            for side in (-1, 1):
                for index, (x1,y1,x2,y2) in enumerate(lines):
                    points = []
                    for sample in range(5):
                        t = sample / 4
                        x = lo.x + (hi.x-lo.x)*(x1+(x2-x1)*t)
                        z = hi.z - (hi.z-lo.z)*(y1+(y2-y1)*t)
                        start = Vector((x, side*(max(abs(lo.y),abs(hi.y))+1), z))
                        hit, normal, _, _ = tree.ray_cast(start, Vector((0,-side,0)))
                        if hit is not None:
                            hit += normal * .006
                            points.append((hit.x,hit.z,-hit.y))
                        else:
                            points.append(None)
                    for a,b in zip(points, points[1:]):
                        if a is None or b is None: continue
                        values = (*a,*b,index//6+1)
                        output.append('\t\t{' + ', '.join(f'{v:.6f}' for v in values) + '},')
                        count += 1
            output.append('\t},')
            report[gid] = count
        finally:
            for obj in objects: bpy.data.objects.remove(obj, do_unlink=True)
            bpy.data.scenes.remove(scene)
    output.append("}")
    with open(repo_path("src", "shared", "Config", "CrackPaths.luau"), "w", encoding="utf-8") as file:
        file.write("\n".join(output)+"\n")
    return report


result = export_crack_paths()
