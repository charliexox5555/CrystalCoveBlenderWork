"""Writes src/shared/Config/ItemIconSheets.luau from the sheet layout and the uploaded image ids.

    python3 tools/icons/write_sheets_config.py

Reads assets/icons/items/sheets/layout.json (tools/icons/make_sheets.py), roblox_assets.json (the uploader's record:
key -> decal asset id) and image_ids.json ({"<decal asset id>": "<image asset id>"}, resolved in Studio with
InsertService:LoadAsset(decal).Decal.Texture).
"""
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DIR = os.path.join(REPO, "assets/icons/items/sheets")


def main():
    layout = json.load(open(os.path.join(DIR, "layout.json")))
    record = json.load(open(os.path.join(DIR, "roblox_assets.json")))["Assets"]
    images = json.load(open(os.path.join(DIR, "image_ids.json")))
    lines = [
        "--!strict",
        "-- Item icon sprite sheets (generated by tools/icons/write_sheets_config.py; do not edit by hand). Small slots",
        "-- (reels, pick-any tiles, reward cells) show their item from one of these sheets instead of the 512 px",
        "-- picture: one small download each, preloaded in the Essential tier and kept warm (Config/LoadTiers,",
        "-- docs/testing/loading/REPORT.md). Cells count left to right, top to bottom; Items maps",
        '-- "<Category>/<id>" to its cell. Rebuild: tools/icons/make_sheets.py, the uploader, then this script.',
        "export type Sheet = { Image: string, Cell: number, Columns: number, Items: { [string]: number } }",
        "local ItemIconSheets = {}",
        "",
        "ItemIconSheets.MaxSlotPixels = 80 -- a slot this size or smaller uses the sheet (cells are 128 px)",
        "",
        "ItemIconSheets.Sheets = {",
    ]
    for sheet in sorted(layout):
        spec = layout[sheet]
        decal = record[f"sheet/{sheet.lower()}"]["AssetId"]
        lines.append(f"\t{sheet} = {{")
        lines.append(f'\t\tImage = "rbxassetid://{images[decal]}",')
        lines.append(f"\t\tCell = {spec['Cell']},")
        lines.append(f"\t\tColumns = {spec['Columns']},")
        lines.append("\t\tItems = {")
        for key, index in sorted(spec["Items"].items(), key=lambda kv: kv[1]):
            lines.append(f'\t\t\t["{key}"] = {index},')
        lines.append("\t\t},")
        lines.append("\t},")
    lines += [
        "} :: { [string]: Sheet }",
        "",
        "-- The sheet and pixel rect for an item, or nil.",
        "function ItemIconSheets.get(category: string, id: string): (string?, Vector2?, Vector2?)",
        '\tlocal key = category .. "/" .. id',
        "\tfor _, sheet in ItemIconSheets.Sheets do",
        "\t\tlocal index = sheet.Items[key]",
        "\t\tif index then",
        "\t\t\tlocal col, row = index % sheet.Columns, index // sheet.Columns",
        "\t\t\treturn sheet.Image, Vector2.new(col * sheet.Cell, row * sheet.Cell), Vector2.new(sheet.Cell, sheet.Cell)",
        "\t\tend",
        "\tend",
        "\treturn nil, nil, nil",
        "end",
        "",
        "return ItemIconSheets",
        "",
    ]
    path = os.path.join(REPO, "src/shared/Config/ItemIconSheets.luau")
    open(path, "w").write("\n".join(lines))
    print("wrote", os.path.relpath(path, REPO))


main()
